namespace CarWash.Hub.Domain.Common;

/// <summary>
/// Marks an aggregate that is edited concurrently and protected by optimistic concurrency.
/// </summary>
/// <remarks>
/// Layer: Domain.
/// <para>
/// The DbContext maps <see cref="RowVersion"/> to a SQL Server <c>rowversion</c> column by
/// convention, so implementing this interface is the whole cost of opting in. A save that lost a
/// race surfaces as <c>409 Concurrency_Conflict</c> and the client reloads.
/// </para>
/// <para>
/// <b>Never update a row-versioned entity on a hot path.</b> <c>rowversion</c> changes on every
/// UPDATE, so stamping, say, a machine's last-seen time on every message would make every admin
/// edit of that machine fail with 409. That is why last-seen is derived from the message index
/// rather than stored on <c>Machine</c>.
/// </para>
/// </remarks>
public interface IHasRowVersion
{
    /// <summary>
    /// Gets or sets the concurrency token. Generated by the database on every write; clients echo
    /// it back (base64) on updates.
    /// </summary>
    byte[] RowVersion { get; set; }
}
